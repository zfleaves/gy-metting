def get_system_template(meeting_type: str, **kwargs) -> str:
    """获取指定会议类型的系统提示词，填充变量"""
    template = SYSTEM_TEMPLATES.get(meeting_type, SYSTEM_TEMPLATES["通用"])
    return template.format(**kwargs)


def get_template_list() -> list[str]:
    """获取所有可用模板列表"""
    return list(SYSTEM_TEMPLATES.keys())