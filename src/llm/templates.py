def get_system_template(meeting_type: str, **kwargs) -> str:
    """
    获取指定会议类型的系统提示词，填充变量。
    使用显式替换而非 str.format()，避免与模板内容中的 {xx} 冲突。
    """
    template = SYSTEM_TEMPLATES.get(meeting_type, SYSTEM_TEMPLATES["通用"])
    # 手动替换已知占位符
    result = template.replace("{meeting_title}", kwargs.get("meeting_title", ""))
    result = result.replace("{background}", kwargs.get("background", ""))
    return result


def get_template_list() -> list[str]:
    """获取所有可用模板列表"""
    return list(SYSTEM_TEMPLATES.keys())